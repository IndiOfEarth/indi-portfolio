export default function ChatPortfolio({ posts = FALLBACK_POSTS }: { posts?: Post[] }) {
  const rootRef = useRef<HTMLDivElement>(null);
  const typedRef = useRef<HTMLSpanElement>(null);
  const sendRef = useRef<HTMLButtonElement>(null);
  const turnRefs = useRef<(HTMLElement | null)[]>([]);
  const [active, setActive] = useState(-1);
  const [value, setValue] = useState("");
  const [focused, setFocused] = useState(false);
  const [nomatch, setNomatch] = useState(false);
  const [sideOpen, setSideOpen] = useState(false);
  const manual = useRef(false);
  manual.current = focused || value.length > 0;

  const goTo = useCallback((i: number) => {
    setSideOpen(false);
    setNomatch(false);
    const el = turnRefs.current[i];
    if (!el) return;
    const top = el.getBoundingClientRect().top + window.scrollY - 64;
    const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    window.scrollTo({ top, behavior: reduce ? "auto" : "smooth" });
  }, []);

  const onSubmit = (e: FormEvent) => {
    e.preventDefault();
    const q = value.trim();
    if (!q) return;
    const i = route(q);
    if (i < 0) { setNomatch(true); return; }
    setValue("");
    (document.activeElement as HTMLElement | null)?.blur();
    goTo(i);
  };

  /* Scroll engine: reveals the conversation as you scroll. */
  useEffect(() => {
    const root = rootRef.current!;
    const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (reduce) root.classList.add("static");

    type S = { el: HTMLElement; words: HTMLElement[]; shown: number; delay: number; caret: number };
    const streams: S[] = Array.from(root.querySelectorAll<HTMLElement>("[data-stream]")).map((el) => ({
      el, words: Array.from(el.querySelectorAll<HTMLElement>(".w")), shown: 0, delay: Number(el.dataset.delay || 0), caret: -1,
    }));
    const users = Array.from(root.querySelectorAll<HTMLElement>("[data-user]"));
    const answers = Array.from(root.querySelectorAll<HTMLElement>("[data-answer]")).map((el) => ({
      el, first: streams.find((s) => el.contains(s.el)),
    }));
    const blocks = Array.from(root.querySelectorAll<HTMLElement>("[data-reveal]"));

    let first = true, last = performance.now(), raf = 0, lastActive = -2, lastTyped = "";

    const setStream = (s: S, n: number) => {
      const prev = Math.round(s.shown), next = Math.round(n);
      if (next > prev) for (let i = prev; i < next; i++) s.words[i]?.classList.add("on");
      else if (next < prev) for (let i = next; i < prev; i++) s.words[i]?.classList.remove("on");
      s.shown = n;
      const c = next > 0 && next < s.words.length ? next - 1 : -1;
      if (c !== s.caret) {
        if (s.caret >= 0) s.words[s.caret]?.classList.remove("caret");
        if (c >= 0 && !reduce) s.words[c]?.classList.add("caret");
        s.caret = c;
      }
    };

    const frame = (now: number) => {
      const dt = Math.min(0.1, (now - last) / 1000); last = now;
      const vh = window.innerHeight;
      const rem = parseFloat(getComputedStyle(document.documentElement).fontSize) || 16;
      const revealY = vh - (6.5 + 2.2) * rem - 28;
      const dock = Math.min(1, Math.max(0, window.scrollY / (vh * 0.55)));
      root.style.setProperty("--dock", dock.toFixed(4));

      // User questions: type into the composer, then send.
      let typing = "";
      let nextFound = false;
      users.forEach((u) => {
        const top = u.getBoundingClientRect().top;
        const on = top < revealY;
        u.classList.toggle("on", on);
        if (!on && !nextFound) {
          nextFound = true;
          const dist = top - revealY, TD = vh * 0.38;
          if (dist < TD && dock > 0.95) {
            const q = u.dataset.q || "";
            typing = q.slice(0, Math.round((1 - dist / TD) * q.length * 1.15));
          }
        }
      });
      if (reduce || manual.current) typing = "";
      if (typing !== lastTyped) {
        lastTyped = typing;
        if (typedRef.current) {
          typedRef.current.textContent = typing;
          typedRef.current.style.display = typing ? "block" : "none";
          typedRef.current.parentElement?.classList.toggle("auto", !!typing);
        }
        sendRef.current?.setAttribute("data-idle", typing || manual.current ? "false" : "true");
      }

      // Streamed paragraphs.
      streams.forEach((s) => {
        const r = s.el.getBoundingClientRect();
        const prog = (revealY - r.top - s.delay) / Math.max(r.height, 30);
        const target = Math.min(1, Math.max(0, prog)) * s.words.length;
        const want = Math.ceil(target - 0.0001);
        if (first || reduce) { setStream(s, want); return; }
        const diff = want - s.shown;
        if (Math.abs(diff) < 0.01) return;
        const rate = diff > 0 ? 75 : 900;
        setStream(s, s.shown + Math.sign(diff) * Math.min(Math.abs(diff), rate * dt));
      });

      // Assistant heads and the thinking state.
      answers.forEach(({ el, first: f }) => {
        const top = el.getBoundingClientRect().top;
        const on = top < revealY;
        el.classList.toggle("on", on);
        el.classList.toggle("thinking", on && !!f && f.shown < 0.5);
      });

      // Rich blocks.
      blocks.forEach((b) => b.classList.toggle("on", b.getBoundingClientRect().top + 24 < revealY));

      // Sidebar position.
      let act = -1;
      turnRefs.current.forEach((t, i) => { if (t && t.getBoundingClientRect().top < vh * 0.45) act = i; });
      if (act !== lastActive) { lastActive = act; setActive(act); }

      first = false;
      raf = requestAnimationFrame(frame);
    };
    raf = requestAnimationFrame(frame);
    return () => cancelAnimationFrame(raf);
  }, []);

  return (
    <PostsContext.Provider value={posts}>
    <div ref={rootRef} className="app">
      <aside className={`side${sideOpen ? " open" : ""}`} aria-label="Conversation">
        <div className="side-top"><span className="side-brand">Indi Caburian</span></div>
        <button type="button" className="new-chat" onClick={() => { setSideOpen(false); window.scrollTo({ top: 0, behavior: "smooth" }); }}>
          <Pencil /> New chat
        </button>
        <h2>Today</h2>
        <ul>
          {TURNS.map((t, i) => (
            <li key={t.id}><button type="button" aria-current={active === i ? "true" : undefined} onClick={() => goTo(i)}>{t.title}</button></li>
          ))}
        </ul>
        <div className="me-tile">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img className="me-photo" src={ASSETS.photoSquare} alt="" />
          <div><b>Indi Caburian</b><span>Final-year CS, predicted First</span></div>
        </div>
      </aside>

      <div className="main">
        <header className="topbar">
          <div style={{ display: "flex", alignItems: "center", gap: ".25rem" }}>
            <button type="button" className="menu-btn" aria-label="Open the conversation list" onClick={() => setSideOpen(true)}><Menu /></button>
            <div className="model">Indi <span>Portfolio, 2026</span></div>
          </div>
          <div className="top-links">
            <a className="pillbtn opt" href="https://github.com/IndiOfEarth">GitHub</a>
            <a className="pillbtn solid" href="mailto:indi.caburian@outlook.com">Email Indi</a>
          </div>
        </header>
        {sideOpen && <button type="button" className="scrim" aria-label="Close the conversation list" onClick={() => setSideOpen(false)} />}

        <section className="hero" aria-labelledby="greet">
          <div className="greet">
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img className="greet-photo" src={ASSETS.photoSquare} alt="" />
            <h1 id="greet">What would you like to know about Indi?</h1>
            <p>Ask a question, pick a suggestion, or just scroll.</p>
          </div>
          <div className="chips">
            {SUGGEST.map((s) => <button key={s.label} type="button" className="chip" onClick={() => goTo(s.turn)}>{s.label}</button>)}
          </div>
          <div className="scroll-hint" aria-hidden="true">Scroll to start the conversation<i /></div>
        </section>

        <main className="thread" id="thread">
          {TURNS.map((t, i) => (
            <section key={t.id} className="turn" id={t.id} ref={(el) => { turnRefs.current[i] = el; }} aria-label={t.q}>
              <div className="u" data-user="" data-q={t.q}><p>{t.q}</p></div>
              <div className="a" data-answer="">
                <div className="a-head"><span className="av" aria-hidden="true">i</span>Indi's portfolio <span className="think">Thinking</span></div>
                <div className="a-body">{t.a}</div>
              </div>
            </section>
          ))}
          <p className="end">That's the tour. Scroll back up, or ask about something specific below.</p>
        </main>

        <div className="dock">
          {nomatch && (
            <div className="nomatch" role="status">
              I can only answer from Indi's portfolio. Try one of these:
              <div>{TURNS.map((t, i) => <button key={t.id} type="button" onClick={() => { setValue(""); goTo(i); }}>{t.title}</button>)}</div>
            </div>
          )}
          <form className="composer" onSubmit={onSubmit}>
            <label htmlFor="ask" className="sr-only">Ask about Indi's work</label>
            <input id="ask" autoComplete="off" value={value} placeholder={focused || value ? "" : "Ask about Indi's work"}
              onChange={(e) => { setValue(e.target.value); setNomatch(false); }} onFocus={() => setFocused(true)} onBlur={() => setFocused(false)} />
            <span ref={typedRef} className="typed" aria-hidden="true" style={{ display: "none" }} />
            <div className="tools">
              <span className="tag">Press Enter to jump to an answer</span>
              <button ref={sendRef} type="submit" className="send" aria-label="Ask" data-idle="true"><ArrowUp /></button>
            </div>
          </form>
          <p className="footnote">This conversation is scripted from Indi's real projects. Nothing here is generated live.</p>
        </div>
      </div>
    </div>
    </PostsContext.Provider>
  );
}
