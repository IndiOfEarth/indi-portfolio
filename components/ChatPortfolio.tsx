function route(text: string): number {
  const t = text.toLowerCase();
  let best = -1, score = 0;
  TURNS.forEach((turn, i) => {
    const s = turn.keys.reduce((n, k) => (t.includes(k) ? n + k.length : n), 0);
    if (s > score) { score = s; best = i; }
  });
  return best;
}

